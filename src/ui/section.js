/**
 * Раздел экрана: заголовок и то, что под ним, — одним блоком.
 *
 * Раньше заголовки и карточки лежали вперемешку соседями в общем списке, и
 * связь между ними держалась только на отступах. Отсюда и лезли перекосы:
 * кнопка в заголовке упиралась в чужую карточку, а расстояние между разделами
 * приходилось подгонять руками в каждом экране отдельно.
 *
 *   section('Курсы валют', [карточка], кнопка)
 *
 * action — то, что стоит справа от заголовка: кнопка или подпись. Может не быть.
 */

import { el } from '../core/dom.js?v=59';

export function section(title, content, action = null) {
  return el('section', { class: 'section' }, [
    el('div', { class: 'section__head' }, [
      el('h2', { class: 'section__title' }, title),
      action,
    ]),
    el('div', { class: 'section__body' }, content),
  ]);
}
